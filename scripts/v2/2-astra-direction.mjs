// v2 stage 2 — gpt-6-astra art-directs the four executions.
// Output is a constrained spec the deterministic compositor consumes: every value is
// something the layout engine can apply literally. Astra never renders text itself.
import fs from "node:fs";
import path from "node:path";
import { ROOT, readInput, readStage, writeStage, extractJson, requireEnv } from "../lib/io.mjs";

const API_KEY = requireEnv("OPENAI_API_KEY");
const MODEL = process.env.ASTRA_MODEL ?? "gpt-6-astra";

const brandKit = readInput("cognition-brand-kit.md");
const copy = readStage("v2-1-claude-copy.json");

function imageParts(dir, label) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => /\.(png|jpg|jpeg|webp)$/i.test(f))
    .map((f) => ({
      file: `${dir}/${f}`,
      label,
      part: {
        type: "input_image",
        image_url: `data:image/png;base64,${fs.readFileSync(path.join(abs, f)).toString("base64")}`,
        detail: "high",
      },
    }));
}
const refs = [...imageParts("inputs/winners", "winner reference"), ...imageParts("brand-refs", "official Cognition lockup")];

const executions = copy.angles.flatMap((a) =>
  a.executions.map((e) => ({
    id: e.id,
    angle: a.title,
    audience: a.audience,
    treatment: e.treatment,
    headline: e.ad.headline,
    support: e.ad.support,
    cta: e.ad.cta,
    artifact: e.artifact,
  })),
);

const instructions = `You are the visual director for a four-execution Devin (Cognition) paid-social set.
You do not write copy and you do not render pixels. You emit a layout specification that a deterministic
compositor applies literally: all text, the official lockup and the CTA button are typeset in code, so your
job is composition, scale, rhythm and restraint. The attached images are official Cognition lockups — visual
truth, not ads to copy.`;

const prompt = `<brand-kit>
${brandKit}
</brand-kit>

<executions>
${JSON.stringify(executions, null, 2)}
</executions>

Canvas: 1080x1350 primary, 1080x1080 adaptation. Same composition, re-flowed.
Typeface is Inter (Regular / Medium / SemiBold) — assume nothing else is available.

The two typography-led executions are pure type: headline, optional support line, lockup, CTA button. No motif.
The two workflow-led executions carry ONE illustrative panel — a clean, flat, text-free work artifact generated by an
image model, which the compositor inserts into a reserved rectangle and labels in code. Suggested territories:
self-serve = a well-scoped ticket card becoming a pull request awaiting human review; enterprise = one task applied
across several repository cards with a review step retained.

Return ONE JSON object, no prose outside it:

{
  "set_direction": "2-3 sentences: how the four read as one system and how the pairs differ",
  "specs": [
    {
      "id": "<execution id, all four, same order as given>",
      "concept_line": "one sentence describing what the viewer sees",
      "ground": "#F7F6F5" | "#FFFFFF" | "#191919",
      "ink": "#191919" | "#F7F6F5",
      "accent_usage": "one short sentence: the single place #317CFF appears, or 'none'",
      "align": "left" | "center",
      "margin_px": <int 72-120, on the 1080 wide canvas>,
      "headline": { "size_px": <int 76-132>, "weight": "medium" | "semibold", "leading": <number 0.95-1.15>, "tracking_px": <number -4 to 0> },
      "support": { "size_px": <int 28-40>, "weight": "regular" | "medium", "color": "ink" | "muted" | "accent" },
      "eyebrow": { "text": "<2-4 word all-caps label or empty string>", "size_px": <int 18-24>, "color": "accent" | "muted" },
      "cta": { "style": "solid-black" | "solid-ink" , "height_px": <int 96-132>, "width": "auto" | "full", "size_px": <int 30-40> },
      "lockup": { "asset": "Cognition_PrimaryLockup_Black.png" | "Cognition_PrimaryLockup_White.png", "position": "top-left" | "bottom-left" | "top-left-with-cta-bottom-right", "height_px": <int 44-72> },
      "vertical_order": ["ordered list from top: any of 'lockup','eyebrow','headline','support','panel','labels','cta'"],
      "panel": {
        "present": true | false,
        "reserved_box": { "x": <int>, "y": <int>, "w": <int>, "h": <int> },
        "label_row": "one short sentence on how the compositor should label the panel stages beneath it",
        "render_prompt": "<literal prompt for the image model, or empty string when present=false>"
      },
      "ratio_adaptation": { "1080x1350": "...", "1080x1080": "what compresses first" },
      "brand_lock_checklist": ["6-8 binary statements a reviewer can verify by looking at the finished render"]
    }
  ]
}

Rules for every "render_prompt" (workflow-led only):
- It renders ONLY the illustrative panel, on a flat uniform background matching the ad ground, at square-ish aspect.
- Absolutely no text, no letters, no numbers, no logos, no watermarks, no UI chrome screenshots, no code.
- Flat vector illustration, editorial, minimal: rectangles, rounded cards, connector lines, one accent colour #317CFF used sparingly.
- Forbid: photography, 3D renders, gradients, drop shadows, paper texture, grain, noise, vignette, neon, purple or magenta,
  robots, mascots, humanoid figures, fake IDE windows, brand logos.
- State the exact hexes and that the background must be perfectly uniform.
- The illustration must be legible as the work artifact even with zero text on it.

Composition rules:
- Default ground #F7F6F5. At most ONE of the four may use #191919, and only an enterprise execution.
- One headline, at most one support sentence, one lockup, one CTA button. Nothing else.
- Each pair must share proposition and CTA and differ in structure, not wording.
- Generous negative space. Subtle borders only. No pill badges, no charts, no decorative lines as filler.
- Keep critical type clear of the outer ${"80"}px on all sides.`;

const res = await fetch("https://api.openai.com/v1/responses", {
  method: "POST",
  headers: { Authorization: `Bearer ${API_KEY}`, "Content-Type": "application/json" },
  body: JSON.stringify({
    model: MODEL,
    instructions,
    input: [{ role: "user", content: [{ type: "input_text", text: prompt }, ...refs.map((r) => r.part)] }],
    max_output_tokens: 20000,
  }),
});
if (!res.ok) throw new Error(`OpenAI ${res.status}: ${await res.text()}`);
const body = await res.json();
const text =
  body.output_text ??
  (body.output ?? []).flatMap((o) => o.content ?? []).filter((c) => c.type === "output_text").map((c) => c.text).join("\n");
const parsed = extractJson(text);

const ids = executions.map((e) => e.id);
const specIds = parsed.specs.map((s) => s.id);
if (specIds.length !== 4 || ids.some((id) => !specIds.includes(id))) throw new Error(`spec mismatch: ${specIds.join(",")}`);
for (const s of parsed.specs) {
  const wantsPanel = executions.find((e) => e.id === s.id).treatment === "workflow-led";
  if (wantsPanel !== Boolean(s.panel?.present)) throw new Error(`panel mismatch for ${s.id}`);
  if (wantsPanel && !s.panel.render_prompt) throw new Error(`missing render_prompt for ${s.id}`);
}

writeStage("v2-2-astra-direction.json", {
  model: MODEL,
  provider: "openai",
  api: "responses",
  generated_at: new Date().toISOString(),
  image_inputs: refs.map((r) => ({ file: r.file, role: r.label })),
  usage: body.usage,
  instructions,
  prompt,
  ...parsed,
});
